def bench_direct(count: int) -> dict:
    sink = Sink()
    echo = threaded_tcp_server(EchoHandler)
    try:
        seconds, moved = push_stream(sink.port, count)
        return summarise(
            "direct",
            seconds,
            moved,
            {
                "conns_per_s": round(connection_rate(echo.server_address[1]), 1),
                "latency_p50_ms": round(statistics.median(latency_samples(echo.server_address[1])), 3),
            },
        )
    finally:
        sink.close()
        echo.shutdown()
        echo.server_close()


def bench_tcp(count: int, closed: bool, tmp: Path) -> dict:
    label = "closed-tcp" if closed else "open-tcp"
    directory = tmp / label
    directory.mkdir(parents=True, exist_ok=True)
    broker = BrokerProcess(
        directory,
        ports=4,
        settings={"broker.connect_rate_per_ip": 5000, "broker.log_level": "warning"},
    )
    broker.start()
    sink = Sink()
    echo = threaded_tcp_server(EchoHandler)
    try:
        tunnel = broker.create_tunnel(f"bench-{label}", proto="tcp", closed=closed)
        agent = start_agent(broker, tunnel, sink.port, "tcp")
        if closed:
            port = free_tcp_port()
            start_peer(broker, tunnel, tunnel["shared_token"], port, "tcp")
        else:
            port = tunnel["public_port"]

        cpu_before = cpu_seconds(broker.process.pid) + cpu_seconds(agent.pid)
        seconds, moved = push_stream(port, count)
        cpu_after = cpu_seconds(broker.process.pid) + cpu_seconds(agent.pid)

        # A second tunnel keeps the throughput stream separate from the
        # connection-rate and latency probes.
        echo_tunnel = broker.create_tunnel(f"bench-{label}-echo", proto="tcp", closed=closed)
        start_agent(broker, echo_tunnel, echo.server_address[1], "tcp", name=f"{label}-echo")
        if closed:
            echo_port = free_tcp_port()
            start_peer(broker, echo_tunnel, echo_tunnel["shared_token"], echo_port, "tcp")
        else:
            echo_port = echo_tunnel["public_port"]

        samples = latency_samples(echo_port)
        return summarise(
            label,
            seconds,
            moved,
            {
                "conns_per_s": round(connection_rate(echo_port), 1),
                "latency_p50_ms": round(statistics.median(samples), 3),
                "latency_p99_ms": round(sorted(samples)[int(len(samples) * 0.99) - 1], 3),
                "cpu_seconds": round(cpu_after - cpu_before, 2),
                "broker_peak_rss_kib": rss_kib(broker.process.pid),
                "agent_peak_rss_kib": rss_kib(agent.pid),
            },
        )
    finally:
        sink.close()
        echo.shutdown()
        echo.server_close()
        broker.cleanup()


def bench_handler(count: int, tmp: Path) -> dict:
    """Throughput with the SDK's Python interception proxy in the path.

    The real topology from the specification is broker -> C agent -> local
    Python proxy -> service, so the agent points at the proxy rather than at the
    service directly. This is expected to be markedly slower than the C fast
    path; that is the documented cost of asking for interception and the reason
    handlers stay off by default.
    """
    directory = tmp / "handler"
    directory.mkdir(parents=True, exist_ok=True)
    broker = BrokerProcess(
        directory,
        ports=4,
        settings={"broker.connect_rate_per_ip": 5000, "broker.log_level": "warning"},
    )
    broker.start()
    sink = Sink()
    listen = free_tcp_port()
    proxy = subprocess.Popen(
        [sys.executable, "-c", _PROXY_SOURCE, str(sink.port), str(listen)],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    try:
        deadline = time.monotonic() + 10
        while time.monotonic() < deadline:
            with socket.socket() as probe:
                if probe.connect_ex(("127.0.0.1", listen)) == 0:
                    break
            time.sleep(0.05)

        tunnel = broker.create_tunnel("bench-handler", proto="tcp", closed=False)
        agent = start_agent(broker, tunnel, listen, "tcp")

        cpu_before = (
            cpu_seconds(broker.process.pid) + cpu_seconds(agent.pid) + cpu_seconds(proxy.pid)
        )
        seconds, moved = push_stream(tunnel["public_port"], count)
        cpu_after = (
            cpu_seconds(broker.process.pid) + cpu_seconds(agent.pid) + cpu_seconds(proxy.pid)
        )
        return summarise(
            "handler",
            seconds,
            moved,
            {
                "cpu_seconds": round(cpu_after - cpu_before, 2),
                "broker_peak_rss_kib": rss_kib(broker.process.pid),
                "proxy_peak_rss_kib": rss_kib(proxy.pid),
                "note": "open tunnel + Python interception proxy; disable handlers for bulk transfer",
            },
        )
    finally:
        proxy.terminate()
        try:
            proxy.wait(timeout=5)
        except subprocess.TimeoutExpired:
            proxy.kill()
        sink.close()
        broker.cleanup()


def bench_udp(count: int, tmp: Path) -> dict:
    directory = tmp / "udp"
    directory.mkdir(parents=True, exist_ok=True)
    broker = BrokerProcess(
        directory,
        ports=4,
        settings={
            "broker.udp_max_packets_per_tunnel": 2_000_000,
            "broker.udp_max_packets_per_source": 2_000_000,
            "broker.udp_flow_creation_rate": 4096,
            "broker.log_level": "warning",
        },
    )
    broker.start()
    echo = UdpEcho()
    echo.start()
    try:
        tunnel = broker.create_tunnel("bench-udp", proto="udp")
        agent = start_agent(broker, tunnel, echo.port, "udp")
        target = ("127.0.0.1", tunnel["public_port"])
        size = 1400
        datagrams = max(1000, count // size)

        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as client:
            client.settimeout(2)
            client.sendto(b"warmup", target)
            try:
                client.recvfrom(65535)
            except TimeoutError:
                pass

            samples = []
            for _ in range(200):
                start = time.perf_counter()
                client.sendto(b"p" * 64, target)
                try:
                    client.recvfrom(65535)
                    samples.append((time.perf_counter() - start) * 1000)
                except TimeoutError:
                    pass

            cpu_before = cpu_seconds(broker.process.pid) + cpu_seconds(agent.pid)
            payload = b"u" * size
            started = time.perf_counter()
            sent = 0
            for _ in range(datagrams):
                try:
                    client.sendto(payload, target)
                    sent += 1
                except OSError:
                    time.sleep(0.0002)
            seconds = time.perf_counter() - started
            cpu_after = cpu_seconds(broker.process.pid) + cpu_seconds(agent.pid)

        time.sleep(1)
        status = broker.status()
        ordered = sorted(samples) or [0.0]
        return summarise(
            "open-udp",
            seconds,
            sent * size,
            {
                "datagrams_sent": sent,
                "datagrams_per_s": round(sent / seconds, 1) if seconds else 0,
                "broker_rx_datagrams": status["datagrams_rx_total"],
                "dropped": (
                    status["udp_dropped_queue_full"]
                    + status["udp_dropped_rate_limit"]
                    + status["udp_dropped_oversize"]
                    + status["udp_dropped_no_flow"]
                ),
                "latency_p50_ms": round(statistics.median(ordered), 3),
                "latency_p99_ms": round(ordered[int(len(ordered) * 0.99) - 1], 3),
                "cpu_seconds": round(cpu_after - cpu_before, 2),
                "broker_peak_rss_kib": rss_kib(broker.process.pid),
            },
        )
    finally:
        echo.close()
        broker.cleanup()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--bytes", default="512MiB", help="payload per throughput run (default 512MiB)")
    parser.add_argument("--modes", default=",".join(ALL_MODES), help=f"comma separated: {','.join(ALL_MODES)}")
    parser.add_argument("--json", type=Path, help="also write results as JSON")
    args = parser.parse_args()

    count = parse_size(args.bytes)
    modes = [m.strip() for m in args.modes.split(",") if m.strip()]
    unknown = [m for m in modes if m not in ALL_MODES]
    if unknown:
        parser.error(f"unknown mode(s): {', '.join(unknown)}")

    results = []
    with tempfile.TemporaryDirectory(prefix="tm-bench-") as raw_tmp:
        tmp = Path(raw_tmp)
        for mode in modes:
            print(f"running {mode}…", file=sys.stderr, flush=True)
            if mode == "direct":
                results.append(bench_direct(count))
            elif mode == "open-tcp":
                results.append(bench_tcp(count, closed=False, tmp=tmp))
            elif mode == "closed-tcp":
                results.append(bench_tcp(count, closed=True, tmp=tmp))
            elif mode == "handler":
                results.append(bench_handler(count, tmp))
            elif mode == "open-udp":
                results.append(bench_udp(count, tmp))

    width = max(len(r["mode"]) for r in results)
    print(f"\nTunnelMate benchmark — payload {args.bytes} per run, loopback")
    print(f"{'mode'.ljust(width)}  {'MiB/s':>9}  {'conns/s':>8}  {'p50 ms':>7}  {'CPU s':>6}  {'RSS KiB':>8}")
    for row in results:
        print(
            f"{row['mode'].ljust(width)}  {row['MiB_per_s']:>9.2f}  "
            f"{row.get('conns_per_s', 0):>8}  {row.get('latency_p50_ms', 0):>7}  "
            f"{row.get('cpu_seconds', 0):>6}  {row.get('broker_peak_rss_kib', row.get('proxy_peak_rss_kib', 0)):>8}"
        )
    baseline = next((r for r in results if r["mode"] == "direct"), None)
    if baseline and baseline["MiB_per_s"]:
        print("\nrelative to direct localhost:")
        for row in results:
            if row["mode"] != "direct":
                print(f"  {row['mode'].ljust(width)}  {row['MiB_per_s'] / baseline['MiB_per_s'] * 100:5.1f}%")

    if args.json:
        args.json.write_text(json.dumps(results, indent=2) + "\n")
        print(f"\nwrote {args.json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
