#!/usr/bin/env python3
"""TunnelMate benchmark: compare direct localhost against the tunnel modes.

Measures throughput, connection rate, latency overhead, CPU and peak RSS for:

    direct        raw localhost TCP, the baseline
    open-tcp      through a public broker port
    closed-tcp    through an authenticated tunnelmate-peer
    handler       through the SDK's Python interception proxy
    open-udp      datagram round trips through a public UDP port

Results are what this machine did, not a claim about any other machine. Payload
is generated, never stored, so no run touches the disk.

    tests/load/benchmark.py --bytes 512MiB
    tests/load/benchmark.py --modes direct,open-tcp --json results.json
"""

from __future__ import annotations

import argparse
import json
import os
import socket
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from harness import (  # noqa: E402
    STREAM_BLOCK,
    BrokerProcess,
    EchoHandler,
    UdpEcho,
    deterministic_bytes,
    free_tcp_port,
    rss_kib,
    start_agent,
    start_peer,
    threaded_tcp_server,
)

ALL_MODES = ("direct", "open-tcp", "closed-tcp", "handler", "open-udp")

# Stand-in for the SDK's interception proxy: identity handler, one thread per
# direction, exactly the shape tunnel.set_message_handler() installs.
_PROXY_SOURCE = """
import socket, socketserver, sys, threading
target = int(sys.argv[1]); listen = int(sys.argv[2])
def handler(direction, data, context):
    return data
class Proxy(socketserver.BaseRequestHandler):
    def handle(self):
        up = socket.create_connection(("127.0.0.1", target))
        def pump(src, dst, direction):
            try:
                while chunk := src.recv(65536):
                    out = handler(direction, chunk, None)
                    if out:
                        dst.sendall(out)
            except OSError:
                pass
            try: dst.shutdown(socket.SHUT_WR)
            except OSError: pass
        t = threading.Thread(target=pump, args=(self.request, up, "peer_to_service"), daemon=True)
        t.start()
        pump(up, self.request, "service_to_peer")
        t.join(timeout=30)
        up.close()
s = socketserver.ThreadingTCPServer(("127.0.0.1", listen), Proxy)
s.daemon_threads = True
s.serve_forever()
"""


def parse_size(text: str) -> int:
    units = {"B": 1, "KIB": 1024, "MIB": 1024**2, "GIB": 1024**3, "KB": 1000, "MB": 10**6, "GB": 10**9}
    upper = text.strip().upper()
    for suffix, factor in sorted(units.items(), key=lambda kv: -len(kv[0])):
        if upper.endswith(suffix):
            return int(float(upper[: -len(suffix)]) * factor)
    return int(upper)


class Sink:
    """A TCP server that counts bytes and reports the total back."""

    def __init__(self) -> None:
        self.server = threaded_tcp_server(self._handler())

    @staticmethod
    def _handler():
        class CountingSink(EchoHandler):
            def handle(self) -> None:  # type: ignore[override]
                total = 0
                while chunk := self.request.recv(65536):
                    total += len(chunk)
                self.request.sendall(f"{total}\n".encode())

        return CountingSink

    @property
    def port(self) -> int:
        return self.server.server_address[1]

    def close(self) -> None:
        self.server.shutdown()
        self.server.server_close()


def push_stream(port: int, count: int, timeout: float = 600.0) -> tuple[float, int]:
    """Send `count` generated bytes at `port`; return (seconds, bytes acked)."""
    started = time.perf_counter()
    with socket.create_connection(("127.0.0.1", port), timeout=30) as client:
        client.settimeout(timeout)
        left = count
        while left:
            chunk = deterministic_bytes(count - left, min(left, STREAM_BLOCK))
            client.sendall(chunk)
            left -= len(chunk)
        client.shutdown(socket.SHUT_WR)
        reply = b""
        while not reply.endswith(b"\n"):
            part = client.recv(4096)
            if not part:
                break
            reply += part
    elapsed = time.perf_counter() - started
    return elapsed, int(reply.strip() or 0)


def connection_rate(port: int, rounds: int = 200) -> float:
    """Connections per second for a trivial request/response."""
    started = time.perf_counter()
    done = 0
    for _ in range(rounds):
        try:
            with socket.create_connection(("127.0.0.1", port), timeout=10) as client:
                client.settimeout(10)
                client.sendall(b"x")
                if client.recv(16):
                    done += 1
        except OSError:
            break
    elapsed = time.perf_counter() - started
    return done / elapsed if elapsed > 0 else 0.0


def latency_samples(port: int, rounds: int = 200) -> list[float]:
    """Round-trip milliseconds on an already-open connection."""
    samples: list[float] = []
    with socket.create_connection(("127.0.0.1", port), timeout=10) as client:
        client.settimeout(10)
        for _ in range(rounds):
            start = time.perf_counter()
            client.sendall(b"ping")
            if client.recv(16):
                samples.append((time.perf_counter() - start) * 1000)
    return samples


def cpu_seconds(pid: int) -> float:
    try:
        fields = Path(f"/proc/{pid}/stat").read_text().rsplit(")", 1)[1].split()
    except (OSError, IndexError):
        return 0.0
    ticks = os.sysconf("SC_CLK_TCK")
    # utime and stime are fields 14 and 15 overall, i.e. 12 and 13 after the comm.
    return (int(fields[11]) + int(fields[12])) / ticks


def summarise(name: str, seconds: float, moved: int, extra: dict) -> dict:
    return {
        "mode": name,
        "bytes": moved,
        "seconds": round(seconds, 3),
        "MiB_per_s": round(moved / seconds / 1048576, 2) if seconds else 0,
        **extra,
    }


