def external_base_url(request: Request) -> str:
    """The origin the caller actually reached us on.

    The API listens on loopback behind a proxy, so `request.url` names
    127.0.0.1 and any URL built from it would be useless to the caller. The
    proxy's forwarded headers are the only source of the public origin.
    """
    forwarded_proto = request.headers.get("x-forwarded-proto", "").split(",")[0].strip()
    forwarded_host = request.headers.get("x-forwarded-host", "").split(",")[0].strip()
    scheme = forwarded_proto or request.url.scheme
    netloc = forwarded_host or request.headers.get("host") or request.url.netloc
    return f"{scheme}://{netloc}".rstrip("/")


