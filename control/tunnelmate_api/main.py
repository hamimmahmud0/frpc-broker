    @app.get(
        "/v1/broker-certificate",
        response_class=PlainTextResponse,
        operation_id="broker_certificate",
    )
    async def broker_certificate() -> PlainTextResponse:
        """The broker's transport certificate, in PEM.

        Nothing is disclosed by this: the broker presents the same bytes to
        anyone who opens a TLS connection to the control port. It exists
        because a deployment running the default self-signed certificate is
        otherwise unusable — the agent verifies by default, and a new user has
        no way to obtain the CA to verify against.

        Only the certificate is ever read. The private key sits beside it in
        the same directory, so the path is fixed by configuration and never
        taken from the request.
        """
        try:
            pem = settings.broker_cert_path.read_text("utf-8")
        except OSError:
            raise APIError(404, "CERTIFICATE_UNAVAILABLE", "No transport certificate is published.")
        # Guard against a misconfigured path pointing at the key: shipping a
        # private key to the Internet would be catastrophic and silent.
        if "PRIVATE KEY" in pem or "BEGIN CERTIFICATE" not in pem:
            raise APIError(404, "CERTIFICATE_UNAVAILABLE", "No transport certificate is published.")
        return PlainTextResponse(
            pem,
            media_type="application/x-pem-file",
            headers={"Cache-Control": "public, max-age=300"},
        )

    @app.get("/v1/downloads", operation_id="list_downloads")
    async def list_downloads(request: Request) -> dict[str, Any]:
        """Release binaries this broker publishes.

        Building the agent from source needs a toolchain and OpenSSL 3.2, which
        a reader may not have and cannot always install. The tarballs here hold
        static musl builds that run on any Linux of the right architecture, so
        the fallback path is a download rather than a build.
        """
        base = external_base_url(request)
        items: list[dict[str, Any]] = []
        try:
            entries = sorted(settings.release_dir.iterdir())
        except OSError:
            entries = []
        for entry in entries:
            if not entry.is_file() or not _RELEASE_NAME.match(entry.name):
                continue
            items.append(
                {
                    "name": entry.name,
                    "size": entry.stat().st_size,
                    "url": f"{base}/v1/download/{entry.name}",
                }
            )
        return {"items": items, "checksums": f"{base}/v1/download/SHA256SUMS" if items else None}

    @app.get("/v1/download/{name}", operation_id="download_release")
    async def download_release(name: str) -> FileResponse:
        """Serve one published release file.

        The name is matched against a whitelist pattern before it is joined, so
        no request can name a parent directory, and the resolved path is
        checked to be a direct child of the release directory in case the
        directory itself contains a symlink out.
        """
        unavailable = APIError(404, "DOWNLOAD_UNAVAILABLE", "No such release file.")
        if not _RELEASE_NAME.match(name):
            raise unavailable
        path = settings.release_dir / name
        try:
            resolved = path.resolve(strict=True)
            root = settings.release_dir.resolve(strict=True)
        except OSError:
            raise unavailable
        if resolved.parent != root or not resolved.is_file():
            raise unavailable
        return FileResponse(
            resolved,
            media_type="application/octet-stream",
            filename=name,
            headers={"Cache-Control": "public, max-age=3600"},
        )

    @app.get("/llms.txt", response_class=PlainTextResponse, operation_id="llms_txt")
    async def llms_txt(request: Request) -> PlainTextResponse:
        """Self-describing usage document, public and unauthenticated.

        Rendered against the origin the caller actually reached us on, so the
        examples are copy-pasteable instead of naming a host the reader may not
        be able to resolve.
        """
        return PlainTextResponse(
            render_llms_txt(settings, external_base_url(request)),
            media_type="text/plain; charset=utf-8",
            headers={"Cache-Control": "public, max-age=300"},
        )

    @app.get("/admin/login", response_class=HTMLResponse, include_in_schema=False)
    async def admin_login_page(request: Request) -> Any:
        if admin_session(request):
            return RedirectResponse("/admin", status_code=303)
        return app.state.templates.TemplateResponse(request, "login.html", {})

    @app.post("/admin/login", include_in_schema=False)
    async def admin_login_form(request: Request) -> Any:
        raw = (await request.body()).decode("utf-8", "replace")
        form = parse_qs(raw)
        username = form.get("username", [""])[0]
        password = form.get("password", [""])[0]
        ip = client_ip(request)
        if not app.state.login_rate.allow(ip, 8, 300):
            return app.state.templates.TemplateResponse(
                request, "login.html", {"error": "Too many attempts."}, status_code=429
            )
        user = (
            app.state.db.connect()
            .execute("SELECT * FROM admin_users WHERE username=?", (username,))
            .fetchone()
        )
        if not user or not verify_password(password, user["password_hash"]):
            audit(app.state.db, "login_failed", username, remote_ip=ip)
            return app.state.templates.TemplateResponse(
                request, "login.html", {"error": "Invalid username or password."}, status_code=401
            )
        token, csrf = secrets.token_urlsafe(32), secrets.token_urlsafe(24)
        app.state.db.connect().execute(
            "INSERT INTO admin_sessions(token_hmac,user_id,csrf_token,created_at,expires_at) VALUES(?,?,?,?,?)",
            (
                capability_hmac(settings.secret_key, token),
                user["user_id"],
                csrf,
                now_s(),
                now_s() + 43200,
            ),
        )
        audit(app.state.db, "login", username, remote_ip=ip)
        response = RedirectResponse("/admin", status_code=303)
        response.set_cookie(
            "tm_admin",
            token,
            httponly=True,
            secure=settings.secure_cookies,
            samesite="strict",
            max_age=43200,
            path="/",
        )
        return response

    @app.get("/admin", response_class=HTMLResponse, include_in_schema=False)
    @app.get("/admin/tunnels", response_class=HTMLResponse, include_in_schema=False)
    async def admin_page(request: Request) -> Any:
        session = admin_session(request)
        if not session:
            return RedirectResponse("/admin/login", status_code=303)
        rows = (
            app.state.db.connect()
            .execute("SELECT * FROM tunnels WHERE deleted=0 ORDER BY created_at DESC LIMIT 500")
            .fetchall()
        )
        ann_rows = (
            app.state.db.connect()
            .execute("SELECT * FROM announcements ORDER BY updated_at DESC LIMIT 500")
            .fetchall()
        )
        runtimes, status = await runtime_map()
        tunnels = [tunnel_public(row, runtimes.get(row["tunnel_id"])) for row in rows]
        return app.state.templates.TemplateResponse(
            request,
            "admin.html",
            {
                "session": session,
                "csrf": session["csrf_token"],
                "tunnels": tunnels,
                "announcements": [announcement_public(row) for row in ann_rows],
                "broker": status,
            },
        )

    return app


